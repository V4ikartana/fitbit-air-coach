"""Build the maintainer's private pattern list, kept outside the repo, for check_public.py and the guard test.

Usage (maintainer only): uv run python scripts/build_private_scan_list.py [--home HOME] [--real tests/fixtures/real]
    [--out LIST] [--user-home PATH] [--extra FILE ...]
--home defaults to $FITBIT_AIR_HOME or ~/.fitbit-air; --out to the scanner's list ($FITBIT_AIR_PRIVATE_SCAN or
~/.fitbit-air/private-scan.txt).

Collects literal values that identify the maintainer and must never be published:
- git: the git user name and e-mail (git config);
- home: the home directory path, plus its last part when that is longer than 4 characters;
- db user ids / db point ids: the digits after users/ in snapshots.payload and raw_points.point_key, and the ids
  after dataPoints/ in raw_points.point_key (at most MAX_POINT_IDS), read from <home>/data/health.db read-only;
- device ids: pairedDevices/<id> in any snapshot, values under DEVICE_KEYS in the paired_devices snapshot and MAC
  addresses in it; each at least 6 characters with a digit;
- fixture ids: users/<digits>, dataPoints/<id> and pairedDevices/<id> in the real fixtures;
- race date: race_date from the profile (config/profile.toml, else data/profile.toml), also as YYYYMMDD,
  DD/MM/YYYY, MM/DD/YYYY and YYYY/MM/DD;
- client secret: client_id and project_id from <home>/secrets/client_secret.json;
- extras: manual additions from private-scan.extra.txt next to the output and from each --extra FILE, so they survive
  a rebuild.
Patterns shorter than 3 characters, purely numeric ones shorter than 6, and any containing the public brand
(BRAND) are dropped. The file is written with mode 0600 (never through a symlink, never inside this repo) under a
"do not commit" header. The script never prints a pattern: it reports only counts per source, and names a source
that failed without its values. It exits 1 when a source looks wrong (a database with no ids, an empty git
identity or one that is the public brand with no extras, an invalid profile, an unreadable extra) and 2 on an
error. The output's missing parent folders are created with mode 0700."""
from __future__ import annotations

import argparse
import importlib.util
import json
import os
import re
import sqlite3
import subprocess
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REAL = ROOT / "tests" / "fixtures" / "real"
EXTRA_NAME = "private-scan.extra.txt"
HEADER = "# generated by scripts/build_private_scan_list.py - private, do not commit\n"
MIN_LEN = 3
MIN_NUMERIC_LEN = 6
MAX_POINT_IDS = 200
BRAND = ("vaikartana", "v4ikartana")  # the public brand: never a private pattern
SOURCES = ("git", "home", "db user ids", "db point ids", "device ids", "fixture ids", "race date", "client secret",
           "extras")
USER_ID = re.compile(r"users/(\d+)")
POINT_ID = re.compile(r"dataPoints/([\w-]{6,})")
DEVICE_ID = re.compile(r"pairedDevices/([\w-]{6,})")
DEVICE_KEYS = {"id", "deviceId", "serialNumber", "serial", "macAddress", "mac"}
MAC = re.compile(r"\b[0-9A-Fa-f]{2}(?:[:-][0-9A-Fa-f]{2}){5}\b")


def _load_check():
    """scripts/check_public.py as a module, reusing an already loaded copy of the same file."""
    path = Path(__file__).resolve().parent / "check_public.py"
    mod = sys.modules.get("check_public")
    if mod is not None and Path(getattr(mod, "__file__", "")).resolve() == path:
        return mod
    spec = importlib.util.spec_from_file_location("check_public", path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["check_public"] = mod  # dataclasses look their module up here
    spec.loader.exec_module(mod)
    return mod


check_public = _load_check()


def default_paths() -> tuple[Path, Path]:
    """(home, output list): FITBIT_AIR_HOME or ~/.fitbit-air, and the scanner's own default list path
    (FITBIT_AIR_PRIVATE_SCAN or ~/.fitbit-air/private-scan.txt), so the builder writes where the scanner reads."""
    home = Path(os.environ.get("FITBIT_AIR_HOME") or "~/.fitbit-air").expanduser()
    return home, Path(check_public.default_private_list()).expanduser()


class BuildError(Exception):
    pass


@dataclass
class Report:
    patterns: list[str]
    counts: dict[str, int]
    problems: list[str] = field(default_factory=list)


def _git_identity() -> tuple[str, str]:
    def get(key: str) -> str:
        try:
            return subprocess.run(["git", "config", key], cwd=ROOT, capture_output=True, text=True).stdout.strip()
        except OSError:
            return ""
    return get("user.name"), get("user.email")


def _unique(values) -> list[str]:
    out: list[str] = []
    for v in values:
        v = str(v).strip()
        if v and v not in out:
            out.append(v)
    return out


def _device_id_ok(value: str) -> bool:
    """A device identifier is at least 6 characters long and holds a digit (so words such as a maker's name never
    reach the list)."""
    return len(value) >= 6 and any(c.isdigit() for c in value)


def _device_values(obj) -> list[str]:
    """Values under DEVICE_KEYS, and MAC addresses in any string, anywhere in a paired_devices payload."""
    out: list[str] = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k in DEVICE_KEYS and isinstance(v, (str, int)) and not isinstance(v, bool):
                out.append(str(v))
            else:
                out += _device_values(v)
    elif isinstance(obj, list):
        for v in obj:
            out += _device_values(v)
    elif isinstance(obj, str):
        out += MAC.findall(obj)
    return out


def _db(db: Path, found: dict[str, list[str]], problems: list[str]) -> None:
    if not db.exists():
        return
    try:
        con = sqlite3.connect(db.resolve().as_uri() + "?mode=ro", uri=True)
    except sqlite3.Error:
        problems.append("db: cannot open the database")
        return
    users, points, devices = [], [], []
    try:
        try:
            for kind, payload in con.execute("select kind, payload from snapshots"):
                payload = payload or ""
                users += USER_ID.findall(payload)
                devices += DEVICE_ID.findall(payload)
                if kind == "paired_devices":
                    try:
                        devices += _device_values(json.loads(payload))
                    except json.JSONDecodeError:
                        problems.append("db: a paired_devices snapshot is not valid JSON")
        except sqlite3.Error:
            problems.append("db: cannot read the snapshots table")
        try:
            for (key,) in con.execute("select point_key from raw_points"):
                users += USER_ID.findall(key or "")
                for p in POINT_ID.findall(key or ""):
                    if p not in points and len(points) < MAX_POINT_IDS:
                        points.append(p)
        except sqlite3.Error:
            problems.append("db: cannot read the raw_points table")
    finally:
        con.close()
    found["db user ids"] = _unique(users)
    found["db point ids"] = points
    found["device ids"] = _unique(d for d in devices if _device_id_ok(str(d).strip()))
    if not users and not points:
        problems.append("db: the database exists but no Google ids were found")


def _fixtures(real_dir: Path, found: dict[str, list[str]], problems: list[str]) -> None:
    if not real_dir.is_dir():
        return
    ids, unreadable = [], 0
    for f in sorted(real_dir.rglob("*.json")):
        try:
            text = f.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            unreadable += 1
            continue
        ids += USER_ID.findall(text) + POINT_ID.findall(text)
        ids += [d for d in DEVICE_ID.findall(text) if _device_id_ok(d)]
    if unreadable:
        problems.append(f"fixtures: {unreadable} file(s) could not be read")
    found["fixture ids"] = _unique(ids)


def _date_forms(value: str) -> list[str]:
    """An ISO date plus its YYYYMMDD, DD/MM/YYYY, MM/DD/YYYY, YYYY/MM/DD, D/M/YYYY, M/D/YYYY and DD.MM.YYYY forms
    (each at least 8 characters, duplicates dropped); other text as it is."""
    m = re.fullmatch(r"(\d{4})-(\d{2})-(\d{2})", value.strip())
    if not m:
        return [value]
    y, mo, d = m.groups()
    ud, um = str(int(d)), str(int(mo))
    return _unique([value, f"{y}{mo}{d}", f"{d}/{mo}/{y}", f"{mo}/{d}/{y}", f"{y}/{mo}/{d}", f"{ud}/{um}/{y}",
                    f"{um}/{ud}/{y}", f"{d}.{mo}.{y}"])


def _race_date(home: Path, found: dict[str, list[str]], problems: list[str]) -> None:
    for sub in ("config", "data"):
        f = home / sub / "profile.toml"
        if f.exists():
            try:
                value = tomllib.loads(f.read_text(encoding="utf-8")).get("race_date")
            except (tomllib.TOMLDecodeError, UnicodeDecodeError):
                problems.append(f"profile: {sub}/profile.toml is not valid TOML")
                return
            found["race date"] = _unique(_date_forms(str(value)) if value else [])
            return


def _client_secret(home: Path, found: dict[str, list[str]], problems: list[str]) -> None:
    f = home / "secrets" / "client_secret.json"
    if not f.exists():
        return
    try:
        data = json.loads(f.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError):
        problems.append("client secret: client_secret.json is not valid JSON")
        return
    values = []
    for section in (data, data.get("installed"), data.get("web")) if isinstance(data, dict) else ():
        if isinstance(section, dict):
            values += [section[k] for k in ("client_id", "project_id") if isinstance(section.get(k), str)]
    found["client secret"] = _unique(values)


def _extras(out: Path, extra_files: list[Path], found: dict[str, list[str]], problems: list[str]) -> None:
    values: list[str] = []
    sibling = out.parent / EXTRA_NAME
    files = ([sibling] if sibling.exists() else []) + [Path(p) for p in extra_files]
    for n, f in enumerate(files, start=1):
        if not f.exists():
            problems.append(f"extras: extra file #{n} was not found")
            continue
        try:
            values += check_public.load_private(f)
        except (OSError, UnicodeDecodeError):
            problems.append(f"extras: extra file #{n} could not be read")
    found["extras"] = _unique(values)


def _keep(p: str) -> bool:
    low = p.casefold()
    if len(p) < MIN_LEN or (p.isdigit() and len(p) < MIN_NUMERIC_LEN):
        return False
    return not any(b in low for b in BRAND)


def _make_private_parents(folder: Path) -> None:
    """Create each missing folder down to `folder` with mode 0700 (existing ones are left as they are)."""
    missing = []
    while not folder.exists():
        missing.append(folder)
        folder = folder.parent
    for d in reversed(missing):
        d.mkdir(mode=0o700)
        d.chmod(0o700)  # mkdir's mode is narrowed by the umask; make it exact


def build_report(home: Path, real_dir: Path, out: Path, git_identity: tuple[str, str] | None = None,
                 user_home: str | None = None, extra_files: list[Path] | None = None) -> Report:
    home, real_dir, out = Path(home), Path(real_dir), Path(out)
    if out.resolve().is_relative_to(ROOT.resolve()):
        raise BuildError("refusing to write the private list inside the repo")
    problems: list[str] = []
    found: dict[str, list[str]] = {s: [] for s in SOURCES}
    name, email = git_identity if git_identity is not None else _git_identity()
    if not name or not email:
        problems.append("git: user.name or user.email is empty")
    found["git"] = _unique([name, email])
    user_home = user_home if user_home is not None else str(Path.home())
    base = Path(user_home).name
    found["home"] = _unique([user_home] + ([base] if len(base) > 4 else []))
    _db(home / "data" / "health.db", found, problems)
    _fixtures(real_dir, found, problems)
    _race_date(home, found, problems)
    _client_secret(home, found, problems)
    _extras(out, extra_files or [], found, problems)
    if any(b in v.casefold() for v in (name, email) for b in BRAND) and not any(_keep(v) for v in found["extras"]):
        problems.append("git: identity is the public brand; list the real name and e-mail in " + EXTRA_NAME)
    patterns = [p for p in _unique(v for s in SOURCES for v in found[s]) if _keep(p)]
    _make_private_parents(out.parent)
    fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC | os.O_NOFOLLOW, 0o600)
    os.fchmod(fd, 0o600)  # an existing file keeps its old mode on open(); tighten it before writing
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(HEADER + "".join(p + "\n" for p in patterns))
    return Report(patterns, {s: len(found[s]) for s in SOURCES}, problems)


def build(home: Path, real_dir: Path, out: Path, git_identity: tuple[str, str] | None = None,
          user_home: str | None = None, extra_files: list[Path] | None = None) -> list[str]:
    return build_report(home, real_dir, out, git_identity, user_home, extra_files).patterns


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--home", default=None, help="the home folder (default: $FITBIT_AIR_HOME or ~/.fitbit-air)")
    ap.add_argument("--real", default=str(DEFAULT_REAL))
    ap.add_argument("--out", default=None, help="the list (default: $FITBIT_AIR_PRIVATE_SCAN or "
                                               "~/.fitbit-air/private-scan.txt)")
    ap.add_argument("--user-home", default=None, help="home path to list (default: the current user's)")
    ap.add_argument("--extra", action="append", default=[], help="extra pattern file (repeatable)")
    a = ap.parse_args(argv)
    default_home, default_out = default_paths()
    out = Path(a.out).expanduser() if a.out else default_out
    home = Path(a.home).expanduser() if a.home else default_home
    try:
        report = build_report(home, Path(a.real).expanduser(), out,
                              git_identity=_git_identity(), user_home=a.user_home,
                              extra_files=[Path(p).expanduser() for p in a.extra])
    except BuildError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    except OSError as e:
        print(f"error: {e.strerror or type(e).__name__}: {check_public.display_path(e.filename)}", file=sys.stderr)
        return 2
    counts = ", ".join(f"{s} {report.counts[s]}" for s in SOURCES)
    print(f"sources: {counts}")
    print(f"wrote {len(report.patterns)} pattern(s) to {check_public.display_path(out)} (mode 0600)")
    for p in report.problems:
        print(f"warning: {p}", file=sys.stderr)
    return 1 if report.problems else 0


if __name__ == "__main__":
    sys.exit(main())
